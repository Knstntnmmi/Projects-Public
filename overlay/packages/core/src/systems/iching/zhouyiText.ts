export const ZHOUYI_TEXT_SOURCE = {
  site: 'zh.wikisource.org',
  pages: '周易 and 周易/<hexagram name> (64 sub-pages), block 易經',
  fetchedOn: '2026-11-19',
  textQuality: '50%',
  secondEdition: '周易本義 (四庫全書本), zh.wikisource.org, Page: 文淵閣四庫全書 0012冊.djvu 722 to 774',
} as const;

export const ZHOUYI_TEXT: readonly ZhouyiHexagramText[] = RAW.map((r, i) => ({
  number: i + 1,
  name: r[0],
  judgment: r[1],
  lines: r[2],
  ...(r.length === 4 ? { extra: r[3] } : {}),
}));

/**
 * One statement by King Wen number and line: 0 is the judgment, 1 to 6 the lines from the
 * bottom, 7 the extra line of hexagram 1 (用九) or 2 (用六). Undefined where none exists.
 */
export function statementText(number: number, line: number): string | undefined {
  const h = ZHOUYI_TEXT[number - 1];
  if (!h) return undefined;
  if (line === 0) return h.judgment;
  if (line === 7) return h.extra;
  return line >= 1 && line <= 6 ? h.lines[line - 1] : undefined;
}

/** Every statement in order of number then line (judgment, lines 1 to 6, extra): 64 + 384 + 2 = 450. */
export function allStatements(): Array<{ number: number; line: number; id: string; text: string }> {
  const out: Array<{ number: number; line: number; id: string; text: string }> = [];
  for (const h of ZHOUYI_TEXT) {
    for (const line of [0, 1, 2, 3, 4, 5, 6, 7]) {
      const text = statementText(h.number, line);
      if (text !== undefined) out.push({ number: h.number, line, id: `${h.number}.${line}`, text });
    }
  }
  return out;
}
